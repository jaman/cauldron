defmodule Megablast.Art do
  @moduledoc """
  The demo's pictures in the atlas `:megablast`: the nebula and the coral loaded from
  `priv/art`, the rock the walls are built from, the turrets, the drones and pods, and the
  ship with its five banks, its drones and its retro flame.

  The ship, the drones, the pods and the turrets were made as sprite sheets and cut into
  frames by `mix linocut.sheet`. The banks are squashed from the ship's one picture and the
  wall tiles are cut from one rock texture.

  `install/0` loads the directory, draws the rest, installs the atlas and gives back its
  name.
  """

  alias Cauldron2D.Atlas

  @name :megablast
  @tile 16
  @void {6, 4, 16}
  @rocks 4
  @banks [{0.4, -1}, {0.7, -1}, {1.0, 0}, {0.7, 1}, {0.4, 1}]

  @spark %{"K" => "#0a0a14", "Y" => "#fff0a0", "O" => "#ff8020"}
  @dust %{"S" => "#8aa0c0"}
  @fire %{"Y" => "#fff0c0", "O" => "#ff9030", "R" => "#d04010"}

  @shot """
  ................
  ................
  .......YY.......
  .......YY.......
  ......YOOY......
  ......YOOY......
  ......YOOY......
  ......KOOK......
  ................
  ................
  ................
  ................
  ................
  ................
  ................
  ................
  """

  @flak """
  ................
  ................
  ................
  ................
  ................
  ......RRRR......
  .....ROOOOR.....
  .....ROYYOR.....
  .....ROYYOR.....
  .....ROOOOR.....
  ......RRRR......
  ................
  ................
  ................
  ................
  ................
  """

  @retro """
  ................
  .......YY.......
  ......YOOY......
  ......ROOR......
  ......ROOR......
  .......RR.......
  ................
  ................
  ................
  ................
  ................
  ................
  ................
  ................
  ................
  ................
  """

  @speck """
  ................
  ................
  ................
  ................
  ................
  ................
  ................
  .......S........
  ................
  ................
  ................
  ................
  ................
  ................
  ................
  ................
  """

  @star """
  ................
  ................
  ................
  ................
  ................
  ................
  .......S........
  ......SSS.......
  .......S........
  ................
  ................
  ................
  ................
  ................
  ................
  ................
  """

  @doc "The atlas name."
  @spec name() :: Atlas.name()
  def name, do: @name

  @doc "The tile size in pixels."
  @spec tile() :: pos_integer()
  def tile, do: @tile

  @doc "The art directory."
  @spec dir() :: Path.t()
  def dir, do: Path.join(:code.priv_dir(:megablast), "art")

  @doc "The ship art for a bank, `-2` hard left through `2` hard right."
  @spec ship(-2..2) :: atom()
  def ship(bank), do: :"ship_#{bank + 2}"

  @doc "The turret art for an open or shut one."
  @spec turret(boolean()) :: atom()
  def turret(true), do: :turret_open
  def turret(_shut), do: :turret_shut

  @doc "Load the directory, draw the rest, install the atlas, and give back its name."
  @spec install() :: Atlas.name()
  def install do
    if Atlas.installed?(@name) do
      @name
    else
      {:ok, atlas} = Atlas.load(@name, dir(), tile: @tile, void: @void)

      atlas
      |> recede()
      |> walls()
      |> guns()
      |> banks()
      |> mines()
      |> motes()
      |> Atlas.install()
    end
  end

  defp recede(atlas) do
    atlas
    |> dim(:nebula, "#06040f", 0.68)
    |> dim(:coral, "#120a20", 0.25)
  end

  defp dim(atlas, art, colour, amount) do
    entry = Atlas.entry(atlas, art)
    raster = entry.frames |> hd() |> Map.fetch!(:raster)

    Atlas.put(atlas, art, Linocut.tint(raster, colour, amount),
      glyph: entry.glyph,
      color: entry.color
    )
  end

  defp walls(atlas) do
    entry = Atlas.entry(atlas, :rock)
    face = entry.frames |> hd() |> Map.fetch!(:raster)

    face
    |> Linocut.frames({@tile, @tile})
    |> Enum.take(@rocks)
    |> Enum.with_index()
    |> Enum.reduce(atlas, fn {raster, index}, acc ->
      Atlas.put(acc, :"rock_#{index}", raster, glyph: entry.glyph, color: entry.color)
    end)
  end

  defp guns(atlas) do
    entry = Atlas.entry(atlas, :turret)
    [shut, open] = Enum.map(entry.frames, & &1.raster)

    atlas
    |> Atlas.put(:turret_shut, shut, glyph: "o ", color: entry.color)
    |> Atlas.put(:turret_open, open, glyph: "O ", color: entry.color)
  end

  defp mines(atlas) do
    entry = Atlas.entry(atlas, :drone)
    hot = Enum.map(entry.frames, &Linocut.tint(&1.raster, "#e0c030", 0.6))

    Atlas.put(atlas, :mine, hot, glyph: "x ", color: {224, 192, 48}, fps: 18)
  end

  defp banks(atlas) do
    entry = Atlas.entry(atlas, :ship)
    level = entry.frames |> hd() |> Map.fetch!(:raster)

    @banks
    |> Enum.with_index()
    |> Enum.reduce(atlas, fn {{share, lean}, index}, acc ->
      Atlas.put(acc, :"ship_#{index}", rolled(level, share, lean),
        glyph: entry.glyph,
        color: entry.color
      )
    end)
  end

  defp rolled(raster, 1.0, 0), do: raster
  defp rolled(raster, share, lean), do: Linocut.squash(raster, {share, 1.0}, lean: lean)

  defp motes(atlas) do
    atlas
    |> Atlas.put(:shot, sprite(@shot, @spark), glyph: "| ", color: {255, 160, 64})
    |> Atlas.put(:flak, sprite(@flak, @fire), glyph: "* ", color: {208, 64, 16})
    |> Atlas.put(:retro, sprite(@retro, @fire), glyph: "^ ", color: {255, 144, 48})
    |> Atlas.put(:speck, sprite(@speck, @dust), glyph: ". ", color: {138, 160, 192})
    |> Atlas.put(:star, sprite(@star, @dust), glyph: "+ ", color: {200, 220, 255})
    |> drone_pod()
  end

  defp drone_pod(atlas) do
    entry = Atlas.entry(atlas, :pod)
    first = entry.frames |> hd() |> Map.fetch!(:raster)

    Atlas.put(atlas, :addon, Linocut.squash(first, {0.7, 0.7}),
      glyph: "p ",
      color: entry.color
    )
  end

  defp sprite(picture, palette), do: Linocut.sprite(picture, palette, size: {@tile, @tile})
end
