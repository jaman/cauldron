  @box ["###", "#.#", "#.#", "#.#", "###"]
  @height 5
  @advance 4

  @doc "The five rows of a character's glyph, `#` for a lit pixel."
  @spec glyph(String.t()) :: [String.t()]
  def glyph(char), do: Map.get(@glyphs, String.upcase(char), @box)

  @doc "How many pixels across `text` renders, before scaling."
  @spec width(String.t()) :: non_neg_integer()
  def width(text), do: max(0, String.length(text) * @advance - 1)

  @doc "The text as a raster in `colour`; option `:scale`, a whole factor (default `1`)."
  @spec render(String.t(), Palette.spec(), keyword()) :: Raster.t()
  def render(text, colour, opts \\ []) do
    rgba = Palette.color(colour)
    chars = String.graphemes(text)
    raster = Raster.new(max(1, width(text)), @height)

    painted =
      for {char, index} <- Enum.with_index(chars),
          {row, y} <- Enum.with_index(glyph(char)),
          {pixel, x} <- Enum.with_index(String.graphemes(row)),
          pixel == "#",
          reduce: raster do
        acc -> Raster.put_pixel(acc, index * @advance + x, y, rgba)
      end

    case Keyword.get(opts, :scale, 1) do
      1 -> painted
      factor -> Linocut.scale(painted, factor)
    end
  end
